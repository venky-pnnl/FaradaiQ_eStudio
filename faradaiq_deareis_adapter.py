"""FaradaIQ -> DearEIS EIS handoff adapter.

This module is intentionally standalone so the FaradaIQ GUI can stream a selected
EIS Plot/view into DearEIS without adding the DearEIS dependency to the required
base environment. DearEIS itself is installed in a separate optional .deareis_venv
on Windows to avoid conflicting with FaradaIQ pinned plotting dependencies. If
DearEIS is available in the current interpreter, the adapter also creates a
native DearEIS project JSON containing the selected spectra.

Credit: DearEIS is developed by the DearEIS developers / Ville Yrjana and is
licensed separately.  See https://vyrjana.github.io/DearEIS/ .
"""
from __future__ import annotations

import argparse
import json
import math
import os
import re
import subprocess
import sys
from dataclasses import dataclass, asdict
from datetime import datetime
from pathlib import Path
from typing import Iterable, List, Optional, Sequence, Tuple

import numpy as np
import pandas as pd


DEAREIS_CREDIT = (
    "DearEIS credit: DearEIS is a free/open-source impedance-spectrum processing, "
    "visualization, validation, DRT, and equivalent-circuit fitting program developed "
    "by the DearEIS developers / Ville Yrjana. FaradaIQ only prepares and launches "
    "a handoff; DearEIS remains a separate third-party project."
)


@dataclass
class EISHandoffItem:
    source_file: str
    normalized_csv: str
    label: str
    n_points: int
    min_frequency_hz: Optional[float]
    max_frequency_hz: Optional[float]
    warnings: List[str]


@dataclass
class EISHandoffResult:
    created: str
    output_dir: str
    normalized_files: List[str]
    manifest: str
    readme: str
    project_json: str
    deareis_available: bool
    warnings: List[str]
    items: List[EISHandoffItem]


def _safe_name(text: str, default: str = "eis") -> str:
    text = str(text or default).strip()
    text = re.sub(r"[^A-Za-z0-9._-]+", "_", text).strip("._-")
    return text or default


def _norm_col(name: object) -> str:
    s = str(name or "").strip().lower()
    s = s.replace("ω", "omega").replace("Ω", "ohm").replace("′", "'").replace("″", "''")
    return re.sub(r"[^a-z0-9]+", "", s)


def _read_table(path: Path) -> pd.DataFrame:
    # Try normal CSV/TSV dialect inference first.  If the file is whitespace-delimited
    # or has comment-heavy headers, fall back to a whitespace parser.
    attempts = [
        dict(sep=None, engine="python", comment="#", on_bad_lines="skip"),
        dict(sep="\t", engine="python", comment="#", on_bad_lines="skip"),
        dict(delim_whitespace=True, engine="python", comment="#", on_bad_lines="skip"),
    ]
    last_exc: Optional[Exception] = None
    for kwargs in attempts:
        try:
            df = pd.read_csv(path, **kwargs)
            if df is not None and df.shape[1] >= 2 and df.shape[0] > 0:
                return df
        except Exception as exc:  # pragma: no cover - diagnostic fallback
            last_exc = exc
    # Try to skip preamble lines until a plausible header or numeric block.
    text = path.read_text(encoding="utf-8", errors="ignore").splitlines()
    for start in range(min(len(text), 80)):
        snippet = "\n".join(text[start:])
        try:
            from io import StringIO
            df = pd.read_csv(StringIO(snippet), sep=None, engine="python", comment="#", on_bad_lines="skip")
            if df.shape[1] >= 2 and df.shape[0] > 0:
                return df
        except Exception as exc:
            last_exc = exc
    raise ValueError(f"Could not read a numeric EIS table from {path}: {last_exc}")


def _numeric_series(df: pd.DataFrame, col: object) -> pd.Series:
    s = df[col]
    if not isinstance(s, pd.Series):
        s = pd.Series(s)
    if s.dtype.kind in "biufc":
        return pd.to_numeric(s, errors="coerce")
    # Clean common thousands separators/ohm suffixes without damaging exponent signs.
    cleaned = s.astype(str).str.replace("Ω", "", regex=False).str.replace("ohm", "", case=False, regex=False)
    cleaned = cleaned.str.replace(",", "", regex=False).str.strip()
    return pd.to_numeric(cleaned, errors="coerce")


def _find_column(df: pd.DataFrame, preferred_tokens: Sequence[str], avoid_tokens: Sequence[str] = ()) -> Optional[object]:
    normalized = {col: _norm_col(col) for col in df.columns}
    for col, n in normalized.items():
        if any(tok in n for tok in avoid_tokens):
            continue
        if any(tok in n for tok in preferred_tokens):
            return col
    return None


def _extract_eis_frame(path: Path) -> Tuple[pd.DataFrame, List[str]]:
    warnings: List[str] = []
    df = _read_table(path)
    if df.empty:
        raise ValueError(f"No rows in {path}")

    # Remove fully-empty columns generated by trailing delimiters.
    df = df.dropna(axis=1, how="all")
    cols_norm = {_norm_col(c): c for c in df.columns}

    f_col = _find_column(df, ["frequency", "freq", "frehz", "fhz", "hz"])
    if f_col is None:
        # If no name helps, assume the first numeric column is frequency.
        numeric_scores = []
        for col in df.columns:
            s = _numeric_series(df, col)
            numeric_scores.append((s.notna().sum(), col))
        numeric_scores.sort(reverse=True, key=lambda x: x[0])
        f_col = numeric_scores[0][1] if numeric_scores else None
        warnings.append("Frequency column was inferred from numeric content because no frequency-like header was found.")
    if f_col is None:
        raise ValueError(f"Could not identify frequency column in {path}")

    re_col = _find_column(df, ["zreal", "realz", "rez", "zre", "zprime", "zohmreal", "zohmre"], avoid_tokens=["imag", "phase", "mag", "mod", "abs"])
    im_col = _find_column(df, ["zimag", "imagz", "imz", "zim", "zdoubleprime", "zbis", "zohmimag", "zohmim"], avoid_tokens=["mag", "mod", "abs", "phase"])

    # Fall back to columns containing Re( or Im( in their original text.
    if re_col is None:
        for col in df.columns:
            raw = str(col).lower()
            if ("re(" in raw or "z'" in raw or "z´" in raw or "real" in raw) and "imag" not in raw:
                re_col = col; break
    if im_col is None:
        for col in df.columns:
            raw = str(col).lower()
            if "im(" in raw or "z''" in raw or "z´´" in raw or "imag" in raw:
                im_col = col; break

    freq = _numeric_series(df, f_col)

    if re_col is not None and im_col is not None:
        zre = _numeric_series(df, re_col)
        zim = _numeric_series(df, im_col)
        raw_im_name = str(im_col).lower().replace(" ", "")
        # Many Nyquist/Bode exports store -Z'' as a positive column.  DearEIS DataSet
        # expects the actual complex imaginary part, so invert when the header makes
        # the sign convention explicit.
        if raw_im_name.startswith("-") or "-z" in raw_im_name or "neg" in raw_im_name or "minus" in raw_im_name:
            zim = -zim
    else:
        mag_col = _find_column(df, ["zmod", "modz", "zmag", "magnitude", "absz", "zabs", "zohm", "impedancemagnitude", "impedancemodulus", "modulus"])
        phase_col = _find_column(df, ["phase", "phasedeg", "theta"])
        if mag_col is None or phase_col is None:
            raise ValueError(f"Could not identify Zreal/Zimag or magnitude/phase columns in {path}")
        mag = _numeric_series(df, mag_col)
        phase_deg = _numeric_series(df, phase_col)
        theta = np.deg2rad(phase_deg.astype(float))
        zre = mag * np.cos(theta)
        zim = mag * np.sin(theta)
        warnings.append("Zreal/Zimag were reconstructed from magnitude and phase columns.")

    out = pd.DataFrame({
        "frequency_Hz": pd.to_numeric(freq, errors="coerce"),
        "Zreal_ohm": pd.to_numeric(zre, errors="coerce"),
        "Zimag_ohm": pd.to_numeric(zim, errors="coerce"),
    })
    out = out.replace([np.inf, -np.inf], np.nan).dropna(subset=["frequency_Hz", "Zreal_ohm", "Zimag_ohm"])
    out = out[out["frequency_Hz"] > 0]
    if out.empty:
        raise ValueError(f"No valid positive-frequency EIS rows were found in {path}")
    out["neg_Zimag_ohm"] = -out["Zimag_ohm"]
    z = out["Zreal_ohm"].to_numpy(float) + 1j * out["Zimag_ohm"].to_numpy(float)
    out["Zmod_ohm"] = np.abs(z)
    out["phase_deg"] = np.rad2deg(np.angle(z))
    return out, warnings


def create_deareis_handoff(
    paths: Iterable[os.PathLike | str],
    output_root: os.PathLike | str,
    label: str = "FaradaIQ selected EIS",
    make_project: bool = True,
) -> EISHandoffResult:
    paths = [Path(p) for p in paths if str(p or "").strip()]
    if not paths:
        raise ValueError("No EIS files were supplied for DearEIS handoff.")
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    outdir = Path(output_root) / f"deareis_eis_handoff_{timestamp}"
    outdir.mkdir(parents=True, exist_ok=True)

    normalized: List[str] = []
    items: List[EISHandoffItem] = []
    warnings: List[str] = []

    for i, path in enumerate(paths, 1):
        try:
            frame, w = _extract_eis_frame(path)
            safe = _safe_name(path.stem or f"eis_{i}")
            out_csv = outdir / f"{i:03d}_{safe}_for_DearEIS.csv"
            frame.to_csv(out_csv, index=False)
            normalized.append(str(out_csv))
            items.append(EISHandoffItem(
                source_file=str(path),
                normalized_csv=str(out_csv),
                label=path.stem or f"EIS {i}",
                n_points=int(len(frame)),
                min_frequency_hz=float(frame["frequency_Hz"].min()) if len(frame) else None,
                max_frequency_hz=float(frame["frequency_Hz"].max()) if len(frame) else None,
                warnings=w,
            ))
            warnings.extend([f"{path.name}: {x}" for x in w])
        except Exception as exc:
            warnings.append(f"Skipped {path}: {exc}")

    if not normalized:
        raise ValueError("No selected file could be converted into frequency/Zreal/Zimag EIS data.\n" + "\n".join(warnings))

    project_json = ""
    deareis_available = False
    if make_project:
        try:
            import deareis  # type: ignore
            deareis_available = True
            project = deareis.Project()
            try:
                project.set_label(label)
            except Exception:
                pass
            try:
                project.set_notes(
                    "Created by FaradaIQ Studio DearEIS handoff on " +
                    datetime.now().isoformat(timespec="seconds") + "\n\n" + DEAREIS_CREDIT
                )
            except Exception:
                pass
            for item in items:
                frame = pd.read_csv(item.normalized_csv)
                f = frame["frequency_Hz"].to_numpy(dtype=float)
                z = frame["Zreal_ohm"].to_numpy(dtype=float) + 1j * frame["Zimag_ohm"].to_numpy(dtype=float)
                ds = deareis.DataSet(frequencies=f, impedances=z, path=item.normalized_csv, label=item.label)
                project.add_data_set(ds)
            proj = outdir / f"{_safe_name(label)}_DearEIS_project.json"
            project.save(str(proj))
            project_json = str(proj)
        except ImportError:
            deareis_available = False
            warnings.append("DearEIS is not installed in this Python environment. Normalized CSVs were still written. On Windows, DearEIS may be installed separately in .deareis_venv and launched with run_deareis_gui.bat.")
        except Exception as exc:
            deareis_available = True
            warnings.append(f"DearEIS project creation failed, but normalized CSVs were written: {exc}")

    manifest_path = outdir / "faradaiq_deareis_handoff_manifest.json"
    readme_path = outdir / "README_DearEIS_handoff.txt"
    result = EISHandoffResult(
        created=datetime.now().isoformat(timespec="seconds"),
        output_dir=str(outdir),
        normalized_files=normalized,
        manifest=str(manifest_path),
        readme=str(readme_path),
        project_json=project_json,
        deareis_available=deareis_available,
        warnings=warnings,
        items=items,
    )
    manifest_payload = asdict(result)
    manifest_path.write_text(json.dumps(manifest_payload, indent=2), encoding="utf-8")
    readme_path.write_text(
        "FaradaIQ -> DearEIS EIS handoff\n"
        "================================\n\n"
        + DEAREIS_CREDIT
        + "\n\nFiles in this folder:\n"
        + "\n".join(f"- {Path(p).name}" for p in normalized)
        + (f"\n\nDearEIS project JSON: {Path(project_json).name}\n" if project_json else "\n\nDearEIS project JSON was not created because DearEIS was not available or project creation failed.\n")
        + "\nInstall DearEIS with:\n"
        + "  install_deareis_optional.bat\n\n"
        + "DearEIS GUI launch command:\n"
        + "  run_deareis_gui.bat\n",
        encoding="utf-8",
    )
    return result


def launch_deareis(project_json: str = "") -> subprocess.Popen:
    # DearEIS officially supports starting via `deareis` or `python -m deareis`.
    # Project-path command line loading is not assumed here, because the documented
    # route is launching the GUI and opening/importing the project/data from there.
    launcher = Path(__file__).resolve().parent / "run_deareis_gui.bat"
    if os.name == "nt" and launcher.exists():
        return subprocess.Popen(["cmd.exe", "/c", str(launcher)], cwd=str(Path(project_json).parent) if project_json else None)
    return subprocess.Popen([sys.executable, "-m", "deareis"], cwd=str(Path(project_json).parent) if project_json else None)


def install_deareis() -> int:
    launcher = Path(__file__).resolve().parent / "install_deareis_optional.bat"
    if os.name == "nt" and launcher.exists():
        return subprocess.call(["cmd.exe", "/c", str(launcher)])
    cmd = [sys.executable, "-m", "pip", "install", "--upgrade", "deareis"]
    return subprocess.call(cmd)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Create a DearEIS handoff bundle from FaradaIQ-selected EIS files.")
    parser.add_argument("paths", nargs="*", help="EIS CSV/TXT files to normalize for DearEIS.")
    parser.add_argument("--manifest", help="JSON manifest containing a 'files' list.")
    parser.add_argument("--output-root", default=".", help="Folder where the DearEIS handoff folder should be created.")
    parser.add_argument("--label", default="FaradaIQ selected EIS", help="DearEIS project label.")
    parser.add_argument("--launch", action="store_true", help="Launch the DearEIS GUI after writing the handoff.")
    parser.add_argument("--install", action="store_true", help="Install/upgrade DearEIS in this Python environment, then exit.")
    args = parser.parse_args(argv)
    if args.install:
        return install_deareis()
    files: List[str] = list(args.paths)
    if args.manifest:
        payload = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
        files.extend(str(p) for p in payload.get("files", []) if p)
    result = create_deareis_handoff(files, args.output_root, label=args.label)
    print(json.dumps(asdict(result), indent=2))
    if args.launch:
        if not result.deareis_available:
            print("DearEIS is not installed. Run with --install or use install_deareis_optional.bat first.", file=sys.stderr)
            return 2
        launch_deareis(result.project_json)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
