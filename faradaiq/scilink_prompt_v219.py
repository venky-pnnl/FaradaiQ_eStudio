def install(core: Mapping[str, Any] | dict[str, Any]) -> None:
    """Install v228 prompt/export overrides into the legacy core namespace."""
    if not isinstance(core, dict):
        raise TypeError("install() requires the faradaiq_studio_core globals dictionary")

    PathType = core.get("Path", Path)
    previous_export = core.get("_v138_export_scilink_handoff") or core.get("_v105_export_scilink_handoff") or core.get("_v101_export_scilink_handoff")

    def latest_handoff(gui: Any = None) -> Path | None:
        finder = core.get("_v105_latest_scilink_handoff")
        if callable(finder):
            try:
                found = finder(gui)
                return Path(found).resolve() if found else None
            except Exception:
                pass
        return None

    def make_prompt(gui: Any, handoff_dir: Any = None, pack: Any = None) -> str:
        handoff = Path(handoff_dir).resolve() if handoff_dir else latest_handoff(gui)
        if handoff is None:
            raise RuntimeError("No SciLink handoff folder found yet. Export a SciLink handoff first.")
        source = None
        if isinstance(pack, dict):
            source = pack.get("source") or pack.get("source_file") or pack.get("source_path")
        if source is None:
            index = handoff / "data_locations_for_scilink.json"
            if index.exists():
                try:
                    loc = json.loads(index.read_text(encoding="utf-8"))
                    source = loc.get("source_file_or_folder") or loc.get("source_run_folder") or loc.get("source_h5")
                except Exception:
                    source = None
        return build_open_scilink_prompt(handoff, source_path=source)

    def refine_prompt(gui: Any, handoff_dir: Any, prompt_text: str, log: Any = None) -> str:
        """Polish wording while preserving the open-ended tool/agent policy."""
        caller = core.get("_v37_call_best_llm")
        if not callable(caller):
            return sanitize_open_prompt(prompt_text)
        try:
            messages = [
                {
                    "role": "system",
                    "content": (
                        "Polish the wording of this SciLink/LabRIC prompt only. Preserve every local path exactly. "
                        "Keep the scientific task open-ended. Do not add agent restrictions, required tool calls, "
                        "forbidden tool calls, mandatory analysis sequences, or limitations on literature use. "
                        "Keep the request focused on examining the data, reporting findings, and returning a next-experiment plan with scientific justification."
                    ),
                },
                {"role": "user", "content": sanitize_open_prompt(prompt_text)},
            ]
            if callable(log):
                log("Sending the open SciLink prompt to the selected LLM for wording refinement...")
            response, provider = caller(messages, max_tokens=3500, temperature=0.0)
            refined = sanitize_open_prompt(str(response or ""))
            if not refined.strip():
                raise RuntimeError("Selected LLM returned an empty prompt.")
            return f"<!-- Refined using {provider} at {datetime.now().isoformat(timespec='seconds')} -->\n\n" + refined
        except Exception as exc:
            if callable(log):
                log(f"Prompt refinement unavailable; using the deterministic open prompt. Reason: {exc}")
            return sanitize_open_prompt(prompt_text)

    def export_handoff(gui: Any = None, parent: Any = None, show_message: bool = True) -> Path:
        if not callable(previous_export):
            raise RuntimeError("SciLink handoff exporter is unavailable.")
        out = Path(previous_export(gui, parent=parent, show_message=False)).resolve()
        (out / "scilink_results").mkdir(parents=True, exist_ok=True)
        _update_location_index(out)
        _write_helper_and_readme(out)
        prompt = make_prompt(gui, handoff_dir=out, pack=None)
        prompt_path = write_open_prompt(out, prompt)
        try:
            if show_message and parent is not None:
                box = core.get("messagebox")
                if box is not None:
                    box.showinfo(
                        "SciLink handoff exported",
                        f"SciLink handoff folder created:\n{out}\n\nOpen-ended scientific prompt saved as:\n{prompt_path}",
                        parent=parent,
                    )
        except Exception:
            pass
        return out

    core["_v218_make_open_scilink_prompt"] = make_prompt
    core["_v105_make_clear_scilink_prompt"] = make_prompt
    core["_v105_refine_scilink_prompt_with_llm"] = refine_prompt
    core["_v218_export_scilink_handoff"] = export_handoff
    core["_v138_export_scilink_handoff"] = export_handoff
    core["_v105_export_scilink_handoff"] = export_handoff
    core["_v101_export_scilink_handoff"] = export_handoff

    help_text = (
        "SciLink open scientific workflow",
        """
SCILINK PROMPT POLICY

FaradaIQ Studio v273 provides the local canonical H5/JSON handoff paths and an open scientific request. The generated prompt does not prescribe select_agent, run_analysis, literature tools, a mandatory agent, or a fixed analysis sequence.

SciLink is invited to examine the current electrochemical data and context using any agents, tools, analyses, coding routes, and literature resources it considers useful. The requested result is intentionally limited to the main findings, the next experiment plan, the scientific justification, important uncertainties or limitations, and a short record of generated outputs.

Both Build open SciLink prompt and Export SciLink handoff use this policy. Optional LLM wording refinement is instructed to preserve the open-ended workflow and exact local paths.
""",
    )
    tabs = core.get("_V207_HELP_TABS")
    if isinstance(tabs, list) and not any(str(item[0]) == help_text[0] for item in tabs if isinstance(item, (list, tuple)) and item):
        tabs.append(help_text)

    def main_final() -> Any:
        core["APP_TITLE"] = "FaradaIQ Studio v273"
        core["FARADAIQ_PUBLIC_VERSION"] = "v237"
        core["FARADAIQ_APP_VERSION"] = "v237"
        entry = core.get("_v80_main")
        if not callable(entry):
            raise RuntimeError("FaradaIQ main GUI entry point is unavailable.")
        return entry()

    core["APP_TITLE"] = "FaradaIQ Studio v273"
    core["FARADAIQ_PUBLIC_VERSION"] = "v237"
    core["FARADAIQ_APP_VERSION"] = "v237"
    core["_v218_main_final"] = main_final
