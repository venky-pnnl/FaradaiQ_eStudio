"""Open-ended SciLink handoff prompt policy for FaradaIQ Studio v273.

The prompt deliberately avoids prescribing SciLink agents, tool calls, analysis
routes, or literature behavior.  It supplies the local data locations and asks
SciLink to examine the experiment, report findings, and propose the next
experiment with scientific justification.
"""
from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path
from typing import Any, Iterable, Mapping

VERSION = "v273"

_FORBIDDEN_LINE_FRAGMENTS = (
    "do not call select_agent",
    "run_analysis, or literature tools",
    "unless the exact scientific request explicitly asks",
    "ground this answer",
)


def sanitize_open_prompt(text: str) -> str:
    """Remove legacy agent/tool restrictions from a generated or refined prompt."""
    kept: list[str] = []
    for line in str(text or "").splitlines():
        low = line.casefold()
        if any(fragment.casefold() in low for fragment in _FORBIDDEN_LINE_FRAGMENTS):
            continue
        # Also remove a legacy compound restriction if wording varies slightly.
        if "do not call" in low and any(token in low for token in ("select_agent", "run_analysis", "literature")):
            continue
        kept.append(line)
    result = "\n".join(kept).strip()
    result = re.sub(r"\n{3,}", "\n\n", result)
    return result + ("\n" if result else "")


def _existing_files(paths: Iterable[Path]) -> list[Path]:
    result: list[Path] = []
    seen: set[str] = set()
    for path in paths:
        try:
            p = Path(path).resolve()
        except Exception:
            p = Path(path)
        key = str(p).casefold()
        if key in seen or not p.exists() or not p.is_file():
            continue
        seen.add(key)
        result.append(p)
    return result


def discover_handoff_files(handoff_dir: Path) -> list[Path]:
    """Return useful local handoff files without prescribing how SciLink uses them."""
    handoff_dir = Path(handoff_dir).resolve()
    candidates: list[Path] = []
    bundle_dir = handoff_dir / "FaradaIQ_bundle"
    if bundle_dir.exists():
        candidates.extend(sorted(bundle_dir.glob("*_faradaiq_bundle.h5")))
        candidates.extend(sorted(bundle_dir.glob("*_faradaiq_bundle.json")))
    for name in (
        "faradaiq_data_context_pack.json",
        "faradaiq_data_context_pack.txt",
        "data_locations_for_scilink.json",
        "faradaiq_scilink_tools.py",
    ):
        candidates.append(handoff_dir / name)
    return _existing_files(candidates)


def build_open_scilink_prompt(
    handoff_dir: str | Path,
    *,
    primary_files: Iterable[str | Path] | None = None,
    output_dir: str | Path | None = None,
    source_path: str | Path | None = None,
) -> str:
    """Create the minimally directive, open-ended SciLink scientific request."""
    handoff = Path(handoff_dir).resolve()
    files = _existing_files(Path(p) for p in primary_files) if primary_files is not None else discover_handoff_files(handoff)
    results = Path(output_dir).resolve() if output_dir is not None else (handoff / "scilink_results").resolve()

    lines = [
        f"# SciLink scientific task generated by FaradaIQ Studio {VERSION}",
        "",
        "## Current FaradaIQ handoff",
        "",
        "```text",
        str(handoff),
        "```",
        "",
    ]
    if source_path:
        lines.extend(["Original source or run location:", "", "```text", str(source_path), "```", ""])
    if files:
        lines.extend(["Available local FaradaIQ files:", ""])
        for p in files:
            lines.append(f"- `{p}`")
        lines.append("")

    lines.extend(
        [
            "## Scientific request",
            "",
            "Examine the current electrochemical data and experiment context. Decide the analysis workflow yourself and use any SciLink capabilities, agents, analysis routes, coding tools, or literature resources that you judge useful.",
            "",
            "Return:",
            "",
            "1. The main scientific findings and interpretation.",
            "2. The next experiment plan.",
            "3. The scientific justification for the proposed next experiment.",
            "4. Important assumptions, uncertainties, limitations, or missing information.",
            "5. A brief record of outputs or files created during the work.",
            "",
            "Save any generated outputs under:",
            "",
            "```text",
            str(results),
            "```",
            "",
            "SciLink has full freedom to choose the appropriate agents, tools, analyses, and literature workflow for this request.",
            "",
        ]
    )
    return sanitize_open_prompt("\n".join(lines))


def write_open_prompt(handoff_dir: str | Path, prompt: str) -> Path:
    handoff = Path(handoff_dir).resolve()
    handoff.mkdir(parents=True, exist_ok=True)
    clean = sanitize_open_prompt(prompt)
    main_path = handoff / "scilink_analysis_prompt.md"
    task_path = handoff / "scilink_task_prompt.md"
    main_path.write_text(clean, encoding="utf-8")
    task_path.write_text(clean, encoding="utf-8")
    return main_path


def _update_location_index(handoff: Path) -> None:
    path = handoff / "data_locations_for_scilink.json"
    data: dict[str, Any] = {}
    if path.exists():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            data = {}
    data.update(
        {
            "app": "FaradaIQ Studio",
            "version": VERSION,
            "prompt_policy": "Open-ended SciLink scientific workflow; no forced agent, analysis, or literature-tool route.",
            "expected_output_folder": str((handoff / "scilink_results").resolve()),
        }
    )
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2, default=str), encoding="utf-8")


